const navItems = [
  { href: '/', label: 'Dashboard', icon: HomeIcon },
  { href: '/eligibility', label: 'Check Eligibility', icon: CheckIcon },
  { href: '/applications', label: 'Applications', icon: FileIcon },
  { href: '/loans', label: 'Active Loans', icon: CreditCardIcon },
  { href: '/collaterals', label: 'Collaterals', icon: LockIcon },
  { href: '/customers', label: 'Customers', icon: UsersIcon, adminOnly: true },
  { href: '/margin-calls', label: 'Margin Calls', icon: AlertIcon, adminOnly: true },
  { href: '/products', label: 'Shop', icon: ShoppingIcon },
  { href: '/loan-products', label: 'Loan Products', icon: SettingsIcon },
  { href: '/activity', label: 'Activity Log', icon: ClockIcon },
  { href: '/api-docs', label: 'API Docs', icon: BookIcon },
];

interface SidebarProps {
  isOpen: boolean;
  onClose: () => void;
}

export default function Sidebar({ isOpen, onClose }: SidebarProps) {
  const pathname = usePathname();
  const router = useRouter();
  const [isAdmin, setIsAdmin] = useState(false);

  useEffect(() => {
    checkUserRole();
  }, []);

  const checkUserRole = async () => {
    try {
      const res = await api.getCurrentUser();
      if (res.success && res.data?.role === 'ADMIN') {
        setIsAdmin(true);
      }
    } catch {}
  };

  const handleLogout = () => {
    api.clearToken();
    router.push('/login');
  };

  const handleNavClick = () => {
    // Close sidebar on mobile after navigation
    if (window.innerWidth < 1024) {
      onClose();
    }
  };

  const filteredNavItems = navItems.filter(item => {
    if ('adminOnly' in item && item.adminOnly) {
      return isAdmin;
    }
    if (item.href === '/loan-products' || item.href === '/api-docs' || item.href === '/activity') {
      return isAdmin;
    }
    return true;
  });

  return (
    <>
      {/* Overlay for mobile */}
      {isOpen && (
        <div 
          className="fixed inset-0 bg-black/50 z-40 lg:hidden"
          onClick={onClose}
        />
      )}
      
      {/* Sidebar */}
      <aside 
        className={`
          fixed left-0 top-0 h-screen w-64 
          bg-[var(--background-secondary)] border-r border-[var(--border)] 
          flex flex-col z-50
          transform transition-transform duration-300 ease-in-out
          ${isOpen ? 'translate-x-0' : '-translate-x-full'}
          lg:translate-x-0
        `}
      >
        {/* Logo */}
        <div className="p-6 border-b border-[var(--border)] flex items-center justify-between">
          <Link href="/" className="block" onClick={handleNavClick}>
            <h1 className="font-bold text-2xl text-[var(--foreground)]">1Fi</h1>
            <p className="text-xs text-[var(--foreground-muted)]">Loan Management</p>
          </Link>
          {/* Close button for mobile */}
          <button 
            onClick={onClose}
            className="lg:hidden p-2 rounded-lg hover:bg-[var(--background-card)] text-[var(--foreground-muted)]"
          >
            <CloseIcon />
          </button>
        </div>

        {/* Navigation */}
        <nav className="flex-1 p-4 space-y-1 overflow-y-auto">
          {filteredNavItems.map((item) => {
            const isActive = pathname === item.href;
            const Icon = item.icon;
            return (
              <Link
                key={item.href}
                href={item.href}
                onClick={handleNavClick}
                className={`nav-item ${isActive ? 'active' : ''}`}
              >
                <Icon />
                <span>{item.label}</span>
              </Link>
            );
          })}
        </nav>

        {/* User section */}
        <div className="p-4 border-t border-[var(--border)] space-y-3">
          <div className="flex items-center justify-between gap-2">
            <span className="text-sm text-[var(--foreground-muted)]">Theme</span>
            <ToggleTheme />
          </div>
          <button 
            onClick={handleLogout}
            className="nav-item w-full text-red-400 hover:text-red-300 hover:bg-red-500/10"
          >
            <LogoutIcon />
            <span>Logout</span>
          </button>
        </div>
      </aside>
    </>
  );
}
